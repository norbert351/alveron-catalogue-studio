export type StudioRole = 'owner' | 'editor';
export type StudioIdentity = { id: string; role: StudioRole };

export function hasStudioAccess(user: StudioIdentity | null | undefined): user is StudioIdentity {
  return user?.role === 'owner' || user?.role === 'editor';
}

export function isSameOrigin(requestUrl: string, origin: string | null, host?: string | null, forwardedProtocol?: string | null): boolean {
  if (!origin) return false;
  try {
    const request = new URL(requestUrl);
    const hostname = host?.split(',')[0]?.trim();
    const protocol = forwardedProtocol?.split(',')[0]?.trim() || request.protocol.slice(0, -1);
    const expected = hostname ? new URL(`${protocol}://${hostname}`).origin : request.origin;
    return new URL(origin).origin === expected;
  }
  catch { return false; }
}

/**
 * Storage keys are generated by this application, never by the browser: they are
 * `<lowercase segment>/<uuid>.<ext>` paths with a fixed set of private extensions.
 * Allow only those shapes so a key can never escape the private root, no matter
 * which storage backend (local filesystem or S3) is resolving it.
 */
const OBJECT_KEY_PATTERN = /^(?:[a-z0-9][a-z0-9_-]*\/)*[a-z0-9][a-z0-9_-]*\.(?:jpg|jpeg|png|webp|pdf)$/;

export const STORAGE_KEY_EXTENSIONS = ['jpg', 'jpeg', 'png', 'webp', 'pdf'] as const;

export function isSafeObjectKey(key: string): boolean {
  if (typeof key !== 'string' || key.length === 0 || key.length > 512) return false;
  if (key.startsWith('/') || key.endsWith('/')) return false;
  if (key.includes('..') || key.includes('//') || key.includes('\\')) return false;
  // Reject control characters and whitespace explicitly (no regex control escapes,
  // so this stays readable and lint-clean).
  for (const character of key) {
    const code = character.codePointAt(0) ?? 0;
    if (code <= 31 || code === 127) return false;
  }
  if (/\s/.test(key)) return false;
  return OBJECT_KEY_PATTERN.test(key);
}
